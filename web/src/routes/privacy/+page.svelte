	<h1>Privacy Policy</h1>
	<p>
		This Privacy Policy explains how the "Are.na screenshotter" Chrome extension
		(the "Extension") collects, uses, and protects your personal information.
	</p>

	<h2>Information Collected</h2>
	<p>
		The Extension does not collect or store any personal information about you,
		such as your name, email address, or browsing history. However, it does
		require certain permissions to function properly:
	</p>
	<ol>
		<li>
			<strong>activeTab</strong>: This permission allows the Extension to access
			the current tab's URL and content for the purpose of capturing
			screenshots.
		</li>
		<li>
			<strong>identity</strong>: This permission enables the Extension to use
			the Chrome Identity API for authenticating with the Are.na service through
			an OAuth 2.0 flow. The Extension does not store or have access to your
			Are.na account credentials.
		</li>
		<li>
			<strong>storage</strong>: This permission allows the Extension to store
			and retrieve data locally, such as access tokens obtained through the
			OAuth flow. No personal information is stored.
		</li>
		<li>
			<strong>host_permissions</strong>: The Extension requires access to make
			requests to various websites, including Are.na's API endpoints, for the
			purpose of uploading screenshots and interacting with the Are.na service.
		</li>
	</ol>

	<h2>Data Usage</h2>
	<p>
		The Extension uses the collected data (access tokens and screenshot images)
		solely for the purpose of providing its intended functionality of capturing
		webpage screenshots and uploading them to your Are.na account. No data is
		shared with third parties or used for any other purposes.
	</p>

	<h2>Data Retention</h2>
	<p>
		Any access tokens or other data stored locally by the Extension are
		automatically removed when the Extension is uninstalled or when the browser
		is closed.
	</p>

	<h2>Security</h2>
	<p>
		The Extension follows industry-standard security practices to protect any
		data stored locally on your device. However, no method of transmission or
		storage is 100% secure, and the Extension cannot guarantee absolute
		security.
	</p>

	<h2>Changes to This Privacy Policy</h2>
	<p>
		The Extension may update this Privacy Policy from time to time. Any changes
		will be posted on this page, and the updated version will be effective as
		soon as it is posted.
	</p>

